let allLoadedProjects = [...FALLBACK_PROJECTS];

function openProjectFancybox(projectId) {
  const project = allLoadedProjects.find(p => p.id === projectId);
  if (!project) return;
  const images = (project.images && project.images.length > 0) ? project.images : [project.image];

  if (typeof Fancybox !== 'undefined') {
    Fancybox.show(
      images.map((src, index) => ({
        src: src,
        type: 'image',
        caption: `
          <div class="text-center font-sans">
            <strong class="text-lg text-white font-semibold">${project.title}</strong>
            <span class="text-xs text-[#8d8c89] block mt-1">${project.category} • ${project.platform} &nbsp;(${index + 1} / ${images.length})</span>
          </div>
        `
      })),
      {
        Carousel: {
          infinite: true,
        },
        Toolbar: {
          display: {
            left: ["infobar"],
            middle: ["zoomIn", "zoomOut", "toggle1to1", "rotateCCW", "rotateCW"],
            right: ["slideshow", "thumbs", "close"],
          },
        },
        Thumbs: {
          autoStart: true,
        },
        Images: {
          zoom: true,
        },
      }
    );
  } else {
    window.open(images[0], '_blank');
  }
}

