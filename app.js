function initScrollSpy() {
  const sectionIds = ['home', 'about', 'projects', 'resume', 'contact'];
  const sections = sectionIds.map(id => document.getElementById(id)).filter(Boolean);
  const navLinks = document.querySelectorAll('.nav-link');
  const header = document.getElementById('main-header');
  if (!navLinks.length || !sections.length) return;

  function updateActiveLink() {
    const scrollPos = window.pageYOffset || document.documentElement.scrollTop;
    const headerH = header ? header.offsetHeight : 120;
    let currentId = '';

    // If reached bottom of page, activate the contact link
    if ((window.innerHeight + scrollPos) >= (document.documentElement.scrollHeight - 80)) {
      currentId = 'contact';
    } else {
      for (let i = 0; i < sections.length; i++) {
        const sec = sections[i];
        const top = sec.offsetTop - (headerH + 40);
        const height = sec.offsetHeight;
        if (scrollPos >= top && scrollPos < top + height) {
          currentId = sec.getAttribute('id');
          break;
        }
      }
    }

    if (!currentId && sections.length > 0) {
      currentId = sections[0].getAttribute('id');
    }

    navLinks.forEach(link => {
      const href = link.getAttribute('href');
      if (href === `#${currentId}`) {
        link.classList.add('active');
      } else {
        link.classList.remove('active');
      }
    });
  }

  window.addEventListener('scroll', updateActiveLink, { passive: true });
  updateActiveLink();
}

function initMobileDrawer() {
  const menuBtn = document.getElementById('mobile-menu-btn');
  const closeBtn = document.getElementById('mobile-drawer-close');
  const drawer = document.getElementById('mobile-drawer');
  const overlay = document.getElementById('mobile-drawer-overlay');
  const mobileNavLinks = document.querySelectorAll('.mobile-nav-link');

  if (!menuBtn || !drawer || !overlay) return;

  function openDrawer() {
    drawer.classList.remove('-translate-x-full');
    drawer.classList.add('translate-x-0');
    overlay.classList.remove('opacity-0', 'pointer-events-none');
    overlay.classList.add('opacity-100', 'pointer-events-auto');
    document.body.classList.add('drawer-open');
  }

  function closeDrawer() {
    drawer.classList.add('-translate-x-full');
    drawer.classList.remove('translate-x-0');
    overlay.classList.add('opacity-0', 'pointer-events-none');
    overlay.classList.remove('opacity-100', 'pointer-events-auto');
    document.body.classList.remove('drawer-open');
  }

  menuBtn.addEventListener('click', openDrawer);
  if (closeBtn) closeBtn.addEventListener('click', closeDrawer);
  overlay.addEventListener('click', closeDrawer);

  mobileNavLinks.forEach(link => {
    link.addEventListener('click', () => {
      closeDrawer();
    });
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && !drawer.classList.contains('-translate-x-full')) {
      closeDrawer();
    }
  });
}

